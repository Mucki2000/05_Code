const ORG = {
  '@context': 'https://schema.org',
  '@type': 'Organization',
  name: 'Lausebengel',
  alternateName: 'Lausebengel Studio',
  url: `${SITE}/`,
  logo: `${SITE}/Logos/favicon.png`,
  image: `${SITE}/assets/og-image.jpg`,
  email: 'info@lausebengel.studio',
  sameAs: ['https://www.instagram.com/lausebengalo/'],
  description: PAGES.en.description,
  knowsAbout: ['Social media production', 'On-set content production', 'Social media strategy', 'Video editing', 'Music videos', 'Brand films'],
};

const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function seoHead(p) {
  const url = SITE + p.path;
  return [
    '<!-- seo:start (generated by tools/build-pages.mjs) -->',
    `  <title>${esc(p.title)}</title>`,
    `  <meta name="description" content="${esc(p.description)}" />`,
    `  <link rel="canonical" href="${url}" />`,
    `  <link rel="alternate" hreflang="de" href="${SITE}/de/" />`,
    `  <link rel="alternate" hreflang="en" href="${SITE}/en/" />`,
    `  <link rel="alternate" hreflang="x-default" href="${SITE}/" />`,
    `  <meta property="og:type" content="website" />`,
    `  <meta property="og:site_name" content="Lausebengel" />`,
    `  <meta property="og:title" content="${esc(p.title)}" />`,
    `  <meta property="og:description" content="${esc(p.description)}" />`,
    `  <meta property="og:url" content="${url}" />`,
    `  <meta property="og:image" content="${SITE}/assets/og-image.jpg" />`,
    `  <meta property="og:image:width" content="1200" />`,
    `  <meta property="og:image:height" content="630" />`,
    `  <meta property="og:locale" content="${p.locale}" />`,
    `  <meta name="twitter:card" content="summary_large_image" />`,
    `  <script type="application/ld+json">${JSON.stringify(ORG)}</script>`,
    '  <!-- seo:end -->',
  ].join('\n');
}

export function render(template, key) {
  const p = PAGES[key];
  let html = template
    .replace(/<!-- seo:start[\s\S]*?<!-- seo:end -->/, seoHead(p))
    .replace(/<h1 class="sr-only">[\s\S]*?<\/h1>/, `<h1 class="sr-only">${esc(p.h1)}</h1>`)
    .replace(/<html[^>]*>/, `<html lang="${p.lang}"${p.dataLang ? ` data-lang="${p.dataLang}"` : ''}>`);
  // Sub-pages: every relative URL (css, js, images, impressum) resolves from the site root.
  if (key !== 'root') html = html.replace('<meta charset="UTF-8" />', '<meta charset="UTF-8" />\n  <base href="/" />');
  return html;
}

