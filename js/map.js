// Label offsets tuned so no two labels overlap; overrides the defaults above.
const LABEL_OFFSETS = {
  LISSABON: { dx: 3, dy: 0 },
  MADRID: { dx: 3, dy: 0 },
  PARIS: { dx: 3, dy: -1 },
  LONDON: { dx: -3, dy: -2, anchor: 'end' },
  NIZZA: { dx: 3, dy: 2 },
  GENF: { dx: -3, dy: 1, anchor: 'end' },
  // ZÜRICH/MÜNCHEN/WIEN sit close together on the grid (y 58-62, x 68-95);
  // the brief's default offsets (ZÜRICH 2/-3, MÜNCHEN 3/1, WIEN 3/0) collide
  // because MÜNCHEN's label alone is ~24 grid units wide. Re-spread them:
  // ZÜRICH drops below-right (clear of PARIS above and MÜNCHEN's row),
  // MÜNCHEN flips to end-anchored on the left, WIEN moves above-left.
  'ZÜRICH': { dx: 3, dy: 5 },
  'MÜNCHEN': { dx: -3, dy: 1, anchor: 'end' },
  BERLIN: { dx: 3, dy: 0 },
  WIEN: { dx: -3, dy: -3, anchor: 'end' },
};

// Run-length encode each row of `#` land cells into one <rect> per run,
// instead of one per cell (MAP_W * MAP_H cells would be ~15,000 rects).
function landRects() {
  const rects = [];
  for (let y = 0; y < MAP_ROWS.length; y++) {
    const row = MAP_ROWS[y];
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (x < row.length && row[x] === '#') x++;
      rects.push(`<rect x="${start}" y="${y}" width="${x - start}" height="1" fill="#1c2e5c" fill-opacity="0.82" />`);
    }
  }
  return rects.join('');
}

function pinMarkup(pin) {
  const { name, x, y } = pin;
  const off = LABEL_OFFSETS[name] || { dx: pin.dx, dy: pin.dy };
  const anchor = off.anchor ? ` text-anchor="${off.anchor}"` : '';
  return `
    <rect class="pin__ring" x="${x - 2.5}" y="${y - 2.5}" width="5" height="5" fill="none" stroke="#e8368f" stroke-width="0.6" />
    <rect x="${x - 1.5}" y="${y - 1.5}" width="3" height="3" fill="#e8368f" />
    <rect x="${x - 0.5}" y="${y - 0.5}" width="1" height="1" fill="#fff" />
    <text x="${x + off.dx}" y="${y + off.dy}" font-family="'Press Start 2P', monospace" font-size="3.4" fill="#1c2e5c" dominant-baseline="middle"${anchor}>${name}</text>`;
}

export function mapSvg() {
  const land = landRects();
  const pins = PINS.map(pinMarkup).join('');
  return `<svg viewBox="0 0 ${MAP_W} ${MAP_H}" shape-rendering="crispEdges" role="img" aria-label="Map of Europe with our locations" xmlns="http://www.w3.org/2000/svg">${land}${pins}</svg>`;
}
